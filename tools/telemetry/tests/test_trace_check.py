class TestFixtures(unittest.TestCase):
    def test_fixtures(self):
        if not FIXTURES_DIR.is_dir():
            self.skipTest(f"fixtures directory not present yet: {FIXTURES_DIR}")
        fixture_paths = sorted(FIXTURES_DIR.glob("*.log"))
        if not fixture_paths:
            self.skipTest(f"no fixture logs found under {FIXTURES_DIR} yet")

        valid_scenarios = set(tc.RULE_BY_SCENARIO) | {"common"}
        valid_expected = {"PASS", "FAIL", "INVALID"}
        failures = []
        for path in fixture_paths:
            parts = path.stem.split("__")
            if len(parts) < 2:
                failures.append(f"{path.name}: filename does not match <scenario>__<EXPECTED>__<desc>.log")
                continue
            scenario, expected = parts[0], parts[1]
            if scenario not in valid_scenarios or expected not in valid_expected:
                failures.append(f"{path.name}: unrecognized scenario/expected in filename")
                continue
            check_scenario = scenario if scenario != "common" else "t1"
            text = path.read_text(encoding="utf-8", errors="replace")
            result = tc.check_log(text, check_scenario)
            if scenario == "common":
                actual = get_outcome(result, "common").status
            else:
                actual = get_outcome(result, tc.RULE_BY_SCENARIO[scenario]).status
            if expected == "PASS":
                ok = actual in ("PASS", "WARN")
            else:
                ok = actual == expected
            if not ok:
                failures.append(f"{path.name}: expected {expected}, got {actual} ({result.render()})")

        if failures:
            self.fail("\n".join(failures))


