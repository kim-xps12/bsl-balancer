class TestGrammarAndPreprocessing(unittest.TestCase):
    def _base(self) -> Log:
        log = Log()
        log.boot()
        sim = GuardSim(log)
        sim.tick(fsm=0, arm=0)
        log.st(fsm=0, arm=0, q=0, conn=0, cing=0, udpr=0, librp=0, ab=0, roff=0, latch=0)
        finish(log, sim, fsm=0, arm=0, q=0, conn=0, udpr=0)
        return log

    def test_boot_missing_is_invalid(self):
        log = Log()
        sim = GuardSim(log)
        sim.tick(fsm=0, arm=0)
        log.st(fsm=0, arm=0, q=0, conn=0, cing=0, udpr=0, librp=0, ab=0, roff=0, latch=0)
        finish(log, sim, fsm=0, arm=0, q=0, conn=0, udpr=0)
        result = tc.check_log(log.text(), "t1")
        self.assertFalse(result.ok)
        self.assertEqual(result.outcomes[0].status, "INVALID")

    def test_multiple_boot_lines_is_invalid(self):
        log = self._base()
        log.boot()
        result = tc.check_log(log.text(), "t1")
        self.assertFalse(result.ok)
        self.assertEqual(result.outcomes[0].status, "INVALID")
        self.assertIn("multiple boot", result.outcomes[0].evidence[0])

    def test_line_before_boot_is_invalid(self):
        log = Log()
        log.tk(fsm=0, arm=0, ep=0)
        log.boot()
        text = log.text()
        result = tc.check_log(text, "t1")
        self.assertFalse(result.ok)
        self.assertEqual(result.outcomes[0].status, "INVALID")

    def test_s_gap_is_invalid(self):
        log = self._base()
        text = log.text()
        lines = text.splitlines()
        # Bump every s value from the 3rd line onward by 1 to create a gap.
        patched = lines[:2]
        for line in lines[2:]:
            tokens = line.split()
            s_val = int(tokens[1][2:])
            tokens[1] = f"s={s_val + 1}"
            patched.append(" ".join(tokens))
        result = tc.check_log("\n".join(patched) + "\n", "t1")
        self.assertFalse(result.ok)
        self.assertEqual(result.outcomes[0].status, "INVALID")
        self.assertIn("gap in s sequence", result.outcomes[0].evidence[0])

    def test_duplicate_s_is_invalid(self):
        log = self._base()
        text = log.text()
        lines = text.splitlines()
        # Force the second line's s to collide with the first.
        tokens = lines[1].split()
        tokens[1] = "s=0"
        lines[1] = " ".join(tokens)
        result = tc.check_log("\n".join(lines) + "\n", "t1")
        self.assertFalse(result.ok)
        self.assertEqual(result.outcomes[0].status, "INVALID")

    def test_malformed_wg1_line_is_invalid(self):
        log = self._base()
        log.raw("[WG1] s=999 t=999999 bogus_record_type foo=bar")
        result = tc.check_log(log.text(), "t1")
        self.assertFalse(result.ok)
        self.assertEqual(result.outcomes[0].status, "INVALID")

    def test_non_wg1_lines_are_ignored(self):
        log = self._base()
        text = "garbled baud-switch noise \xff\xfe\n" + log.text()
        result = tc.check_log(text, "t1")
        self.assertEqual(get_outcome(result, "preprocessing").status, "PASS")
        self.assertEqual(get_outcome(result, "common").status, "PASS")

    def test_missing_required_field_is_invalid(self):
        log = Log()
        log.boot()
        # Hand-craft a tk line missing `ep`.
        log.raw(f"[WG1] s=1 t=50000 tk fsm=0 arm=0")
        result = tc.check_log(log.text(), "t1")
        self.assertFalse(result.ok)
        self.assertEqual(result.outcomes[0].status, "INVALID")


