"""Unit tests for bsl_telemetry.trace_check (Wi-Fi guard [WG1] trace judge).

Covers docs/plans/2026-07-06-wifi-guard-trace-bench.md section 5's PASS/FAIL/
INVALID synthetic-log requirements for R1-R5 + common validity + R4. Hand-
built logs use a small line-builder (`Log`) plus a tick/epoch simulator
(`GuardSim`) that reproduces the emitter's tk-ep/ev-i bookkeeping precisely
enough to exercise the drain-attribution rule (section 5 "イベント起点窓の
drain アンカー") including both interleavings.

Fixture-driven cross-validation (section 4 D11: emitter-generated logs in
tools/telemetry/tests/fixtures/<scenario>__<EXPECTED>__<desc>.log) is
generated by a separate, concurrently-running work item; if the fixtures
directory is empty at test time, TestFixtures.test_fixtures skips itself
(reported explicitly, not silently).
"""

from __future__ import annotations

import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from bsl_telemetry import trace_check as tc

TICK_US = 50_000  # 20 Hz nominal telemetry tick (matches trace_check's default)
FIXTURES_DIR = Path(__file__).resolve().parent / "fixtures"


def _f(v):
    return "-" if v is None else str(v)


class Log:
    """Minimal [WG1] line builder. `s` is assigned in call order (matching
    physical file order), `t` is whatever the caller has advanced to.
    """

    def __init__(self):
        self.lines = []
        self._s = 0
        self.t = 0

    def _emit(self, body: str) -> None:
        self.lines.append(f"[WG1] s={self._s} t={self.t} {body}")
        self._s += 1

    def raw(self, line: str) -> None:
        """Escape hatch for deliberately malformed/corrupted lines."""
        self.lines.append(line)
        self._s += 1

    def boot(self, v=1, fw="abc1234", dev="core2-a4cf"):
        self._emit(f"boot v={v} fw={fw} dev={dev}")

    def tk(self, fsm, arm, ep):
        self._emit(f"tk fsm={_f(fsm)} arm={_f(arm)} ep={ep}")

    def ev(self, kind, r=None, i=None):
        self._emit(f"ev={kind} r={_f(r)} i={_f(i)}")

    def op(self, kind, fsm, arm, q, udpr, res=0, dur=1000, fsm2=None, arm2=None, fsm3=None, arm3=None):
        body = f"op={kind} fsm={_f(fsm)} arm={_f(arm)} q={q} udpr={udpr} res={_f(res)} dur={dur}"
        if kind == "bp":
            body += f" fsm2={_f(fsm2)} arm2={_f(arm2)} fsm3={_f(fsm3)} arm3={_f(arm3)}"
        self._emit(body)

    def st(self, fsm, arm, q, conn, cing, udpr, librp, ab, roff, latch, pwf=0, sf=0, evo=0):
        self._emit(
            f"st fsm={_f(fsm)} arm={_f(arm)} q={q} conn={conn} cing={cing} udpr={udpr} "
            f"librp={librp} ab={ab} roff={roff} latch={latch} pwf={pwf} sf={sf} evo={evo}"
        )

    def hb(self, fsm, arm, q, conn, cing, udpr, librp, ab, roff, latch, pwf=0, sf=0, evo=0,
           heap=100000, heapmin=90000, evdrop=0, flmax=1000, stkmin=4000, tick=0):
        self._emit(
            f"hb fsm={_f(fsm)} arm={_f(arm)} q={q} conn={conn} cing={cing} udpr={udpr} "
            f"librp={librp} ab={ab} roff={roff} latch={latch} pwf={pwf} sf={sf} evo={evo} "
            f"heap={heap} heapmin={heapmin} evdrop={evdrop} flmax={flmax} stkmin={stkmin} tick={tick}"
        )

    def drop(self, n):
        self._emit(f"drop n={n}")

    def advance(self, us):
        self.t += us

    def text(self):
        return "\n".join(self.lines) + "\n"


class GuardSim:
    """Reproduces the emitter's tk.ep (pre-drain cumulative drained count)
    and ev.i (guard-tracked arrival counter) bookkeeping precisely, so hand-
    built logs can exercise trace_check's epoch-based drain attribution
    (section 5) under either interleaving:

      - `event()` then `tick()` (or `tick_start()`+`drain_pending()` in the
        same call): the event drains in the tick whose `tick_start()` prints
        the *old* (pre-event) `ep` and whose `drain_pending()` call is the
        first to include it -- i.e. the current tick.
      - `tick()` (draining nothing new) then `event()` then the *next*
        `tick()`: the event is only visible to guard from the next tick's
        drain onward -- i.e. it is pre-drain for the current tick.
    """

    def __init__(self, log: Log, tick_us: int = TICK_US):
        self.log = log
        self.tick_us = tick_us
        self.drained = 0
        self.arrived = 0
        self.pending = []
        self.tick_count = 0

    def event(self, kind: str, r=None) -> int:
        self.arrived += 1
        self.log.ev(kind, r=r, i=self.arrived)
        self.pending.append(kind)
        return self.arrived

    def library_event(self, kind: str, r=None) -> None:
        self.log.ev(kind, r=r, i=None)

    def tick_start(self, fsm, arm) -> int:
        self.log.advance(self.tick_us)
        self.log.tk(fsm=fsm, arm=arm, ep=self.drained)
        idx = self.tick_count
        self.tick_count += 1
        return idx

    def drain_pending(self) -> None:
        self.drained += len(self.pending)
        self.pending = []

    def tick(self, fsm, arm) -> int:
        idx = self.tick_start(fsm, arm)
        self.drain_pending()
        return idx


CLEAN_TAIL_CTX = dict(conn=1, cing=0, udpr=1, librp=0, ab=0, roff=0, latch=0)


def finish(log: Log, sim: GuardSim, fsm, arm, q, **overrides) -> None:
    """Append >= 2 clean hb rows well after the last activity, satisfying
    the common-validity tail requirements (hb>=2, last line hb, hb after
    last ev/op; section 5 "ログ末尾・カバレッジの完全性").
    """
    ctx = dict(CLEAN_TAIL_CTX)
    ctx.update(overrides)
    for k in range(2):
        log.advance(1_000_000)
        sim.tick(fsm=fsm, arm=arm)
        log.hb(fsm=fsm, arm=arm, q=q, tick=sim.tick_count, **ctx)


def get_outcome(result: tc.CheckResult, name: str) -> tc.Outcome:
    return next(o for o in result.outcomes if o.name == name)


