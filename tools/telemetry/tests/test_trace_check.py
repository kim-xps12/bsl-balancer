class TestR1(unittest.TestCase):
    def test_pass_quiet_balancing_window(self):
        log = Log()
        log.boot()
        sim = GuardSim(log)
        sim.tick(fsm=0, arm=0)
        log.st(fsm=0, arm=0, q=0, conn=0, cing=0, udpr=0, librp=0, ab=0, roff=0, latch=0)
        log.op("bp", fsm=0, arm=0, q=0, udpr=0, dur=800, fsm2=0, arm2=0, fsm3=0, arm3=0)  # genuine first setup bp
        sim.tick(fsm=1, arm=0)
