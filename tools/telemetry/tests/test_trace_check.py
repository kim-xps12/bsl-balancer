        finish(log, sim, fsm=1, arm=0, q=0)

        result = tc.check_log(log.text(), "t1")
        self.assertFalse(result.ok)
        outcome = get_outcome(result, "R1")
        self.assertEqual(outcome.status, "FAIL")
        self.assertIn("ev=scan", outcome.evidence[0])

